// Tool describes the invoked tool.
type Tool struct {
	Name      string `json:"name"`
	Category  string `json:"category,omitempty"`
	Operation string `json:"operation,omitempty"`
	MCPServer string `json:"mcp_server,omitempty"`
	MCPTool   string `json:"mcp_tool,omitempty"`
}

// Target is the primary, safe, bounded label of what a tool acted on.
type Target struct {
	Kind  string `json:"kind"`
	Label string `json:"label"`
}

// Resource is a File/MCP/Process/Network resource linked to a tool call.
type Resource struct {
	Kind     string `json:"kind"`
	Label    string `json:"label"`
	Relation string `json:"relation"`
	Evidence string `json:"evidence"`
}

// Event is the normalized, sanitized event.
type Event struct {
	SchemaVersion int               `json:"schema_version"`
	EventID       string            `json:"event_id"`
	Timestamp     time.Time         `json:"timestamp"`
	HostID        string            `json:"host_id"`
	Harness       string            `json:"harness"`
	SessionID     string            `json:"session_id,omitempty"` // native (source) session id
	TurnID        string            `json:"turn_id,omitempty"`
	ToolCallID    string            `json:"tool_call_id,omitempty"`
	AgentID       string            `json:"agent_id,omitempty"`
	Type          string            `json:"type"`
	SourceEvent   string            `json:"source_event,omitempty"` // native hook event name
	Workspace     string            `json:"workspace,omitempty"`    // home-collapsed workspace path
	Tool          *Tool             `json:"tool,omitempty"`
	Target        *Target           `json:"target,omitempty"`
	Resources     []Resource        `json:"resources,omitempty"`
	Status        string            `json:"status,omitempty"`
	Evidence      string            `json:"evidence"`
	Privacy       string            `json:"privacy"`
	DurationMS    *int64            `json:"duration_ms,omitempty"`
	Attrs         map[string]string `json:"attrs,omitempty"` // allowlisted, bounded extras
}

// Validate checks structural invariants of a sanitized event.
func (e *Event) Validate() error {
	var errs []string
	if e.SchemaVersion != SchemaVersion {
		errs = append(errs, fmt.Sprintf("schema_version %d unsupported", e.SchemaVersion))
	}
	if e.EventID == "" || len(e.EventID) > 96 {
		errs = append(errs, "event_id missing or too long")
	}
	if !KnownTypes[e.Type] {
		errs = append(errs, fmt.Sprintf("unknown type %q", e.Type))
	}
	if e.Timestamp.IsZero() {
		errs = append(errs, "timestamp missing")
	}
	switch e.Harness {
	case HarnessClaude, HarnessCodex, HarnessAtlas:
	default:
		errs = append(errs, fmt.Sprintf("unknown harness %q", e.Harness))
	}
	if e.Type != TypeTelemetryGap && e.SessionID == "" {
		errs = append(errs, "session_id missing")
	}
	if !ValidEvidence(e.Evidence) {
		errs = append(errs, fmt.Sprintf("bad evidence %q", e.Evidence))
	}
	for _, r := range e.Resources {
		if !ValidEvidence(r.Evidence) || r.Kind == "" || r.Label == "" {
			errs = append(errs, "bad resource")
		}
	}
	if e.Privacy != PrivacyMetadataOnly {
		errs = append(errs, "privacy must be metadata_only")
	}
	if len(errs) > 0 {
		return errors.New(strings.Join(errs, "; "))
	}
	return nil
}

var idCounter atomic.Uint32

// NewID returns a roughly time-sortable unique id: prefix + 13 hex chars of
// unix-micro time + 4 hex chars counter + 8 hex random chars.
func NewID(prefix string) string {
	var b [4]byte
	_, _ = rand.Read(b[:])
	return fmt.Sprintf("%s%013x%04x%s", prefix, time.Now().UnixMicro(), idCounter.Add(1)&0xffff, hex.EncodeToString(b[:]))
}
